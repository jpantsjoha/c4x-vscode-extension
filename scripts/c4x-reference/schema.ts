/**
 * JSON Schema (draft 2020-12) for docs/reference/c4x-reference.json.
 *
 * Consumers (the skill, the MCP resources, the extension's prompt) can rely on
 * this shape. Every object is closed: a field the schema does not name fails
 * validation, so a change to the generated shape forces a change here and a
 * bump of `schemaVersion` when it breaks a reader. The unit tests validate the
 * committed reference against this schema.
 */

type Schema = { [key: string]: unknown };

const str: Schema = { type: 'string' };
const bool: Schema = { type: 'boolean' };
const int: Schema = { type: 'integer', minimum: 0 };
const strings: Schema = { type: 'array', items: str };
const severity: Schema = { enum: ['info', 'warning', 'error'] };

function obj(properties: { [key: string]: Schema }, optional: readonly string[] = []): Schema {
    return {
        type: 'object',
        properties,
        required: Object.keys(properties).filter(key => !optional.includes(key)).sort(),
        additionalProperties: false,
    };
}

function list(items: Schema): Schema {
    return { type: 'array', items };
}

const placementScopes = obj({
    Container_Boundary: strings,
    Enterprise_Boundary: strings,
    Node: strings,
    System_Boundary: strings,
    root: strings,
});

const diagnostic = obj({
    id: { type: 'string', pattern: '^C4X-[A-Z0-9]+$' },
    severity,
    summary: str,
    message: str,
    trigger: str,
});

